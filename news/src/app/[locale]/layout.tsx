import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { notFound } from "next/navigation";
import "../globals.css"; // Note the path relative to app/[locale]

import Header from "../components/Header";
import CategoryGrid from "../components/CategoryGrid";
import Footer from "../components/Footer";
import TranslationProvider from "../components/TranslationProvider";
import { fetchCategories } from "../lib/fetch";
import CategoryPage from "./section/[slug]/page";
import { isValidLocale, SUPPORTED_LOCALES } from "@/types/locale";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
  icons: {
    icon: "/tikvah.ico", // Points directly to public/new.ico
  },
};


// (Optional) Statically generate pages for these locales at build time
export function generateStaticParams() {
  return SUPPORTED_LOCALES.map((locale) => ({ locale }));
}

export default async function LocaleLayout({
  children,
  params,
}: Readonly<{
  children: React.ReactNode;
  params: Promise<{ locale: string }>;
}>) {
  // 1. Await params to read the locale URL segment
  const { locale } = await params;

  // 2. Safeguard against unknown locales (e.g. /fr)
  if (!isValidLocale(locale)) {
    notFound();
  }

  // 3. Fetch categories for shared layout elements
  const categories = (await fetchCategories(locale))?.data || [];

  return (
    <html
      lang={locale}
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">
        <TranslationProvider>
          <Header sections={categories} />
          <main className="flex-1">{children}</main>
          <CategoryGrid categories={categories} />
          <Footer />
        </TranslationProvider>
      </body>
    </html>
  );
}